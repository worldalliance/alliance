// Generates src/generated/types.ts from the JSON Schemas in src/schemas.ts, so the types can't drift from them.
// `node scripts/gen-types.mjs --check` exits 1 if the committed file is out of date (the test suite runs this).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { compile } from "json-schema-to-typescript";
import { transcriptSchema, exportSchema, CATEGORY_IDS, CATEGORY_ENUM_NAMES } from "../src/schemas.ts";

const out = new URL("../src/generated/types.ts", import.meta.url);
const opts = { bannerComment: "", additionalProperties: false, strictIndexSignatures: true, format: true, unknownAny: true, enableConstEnums: false, ignoreMinAndMaxItems: true };
const copy = o => structuredClone(o);

// The transcript schema declares KoraCategory as a real enum; the export schema refers to it by name.
const t = copy(transcriptSchema);
t.$defs.category.tsEnumNames = [...CATEGORY_ENUM_NAMES];
if (CATEGORY_ENUM_NAMES.length !== CATEGORY_IDS.length) throw new Error("CATEGORY_ENUM_NAMES and CATEGORY_IDS differ in length");
const e = copy(exportSchema);
delete e.$defs.category;
const inlineCategory = o => {
  if (Array.isArray(o)) return o.map(inlineCategory);
  if (!o || typeof o !== "object") return o;
  if (o.$ref === "#/$defs/category") return { tsType: "KoraCategory" };
  return Object.fromEntries(Object.entries(o).map(([k, v]) => [k, inlineCategory(v)]));
};
Object.assign(e, inlineCategory(e));

const header = `/* eslint-disable */
// GENERATED by scripts/gen-types.mjs from src/schemas.ts. Do not edit by hand: change the schema and run \`npm run gen:types\`.
`;
const body = header + "\n" + (await compile(t, "KoraTranscript", opts)) + "\n" + (await compile(e, "KoraExport", opts));

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch {}
  if (current !== body) { console.error("src/generated/types.ts is out of date. Run `npm run gen:types`."); process.exit(1); }
  console.log("src/generated/types.ts is up to date.");
} else {
  mkdirSync(new URL("./", out), { recursive: true });
  writeFileSync(out, body);
  console.log("Wrote src/generated/types.ts");
}

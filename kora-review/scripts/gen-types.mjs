// Generates src/types.gen.ts from the JSON Schemas in src/schemas.ts, so the types can't drift from them.
// `node scripts/gen-types.mjs --check` exits 1 if the committed file is out of date (the test suite runs this).
import { compile } from "json-schema-to-typescript";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import {
  CATEGORY_ENUM_NAMES,
  CATEGORY_IDS,
  exportSchema,
  itemSchema,
  transcriptSchema,
} from "../src/schemas.ts";

const out = new URL("../src/types.gen.ts", import.meta.url);
const opts = {
  bannerComment: "",
  additionalProperties: false,
  strictIndexSignatures: true,
  format: true,
  unknownAny: true,
  enableConstEnums: false,
  ignoreMinAndMaxItems: true,
};
const copy = (o) => structuredClone(o);

// The first schema compiled declares KoraCategory as a real enum, and the shared turn types; the schemas
// after it refer to all three by name, so each type is declared once in the generated file.
const t = copy(transcriptSchema);
t.$defs.category.tsEnumNames = [...CATEGORY_ENUM_NAMES];
if (CATEGORY_ENUM_NAMES.length !== CATEGORY_IDS.length)
  throw new Error("CATEGORY_ENUM_NAMES and CATEGORY_IDS differ in length");

const SHARED = {
  "#/$defs/category": "KoraCategory",
  "#/$defs/conversation": "KoraConversation",
  "#/$defs/turn": "KoraTurn",
};
const inlineShared = (o) => {
  if (Array.isArray(o)) return o.map(inlineShared);
  if (!o || typeof o !== "object") return o;
  if (SHARED[o.$ref]) return { tsType: SHARED[o.$ref] };
  return Object.fromEntries(
    Object.entries(o).map(([k, v]) => [k, inlineShared(v)]),
  );
};
const sharing = (schema) => {
  const copied = inlineShared(copy(schema));
  for (const name of ["category", "conversation", "turn"])
    delete copied.$defs[name];
  return copied;
};
const i = sharing(itemSchema);
const e = sharing(exportSchema);

const header = `// GENERATED by scripts/gen-types.mjs from src/schemas.ts. Do not edit by hand: change the schema and run \`bun run gen:types\`.
`;
const body =
  header +
  "\n" +
  (await compile(t, "KoraTranscript", opts)) +
  "\n" +
  (await compile(i, "KoraItem", opts)) +
  "\n" +
  (await compile(e, "KoraExport", opts));

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== body) {
    console.error("src/types.gen.ts is out of date. Run `bun run gen:types`.");
    process.exit(1);
  }
  console.log("src/types.gen.ts is up to date.");
} else {
  mkdirSync(new URL("./", out), { recursive: true });
  writeFileSync(out, body);
  console.log("Wrote src/types.gen.ts");
}
